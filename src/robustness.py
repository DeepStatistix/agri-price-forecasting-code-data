"""Robustness tables from saved forecasts only: (1) half-window stability (first 26 vs last 26 test origins),
(2) within-season-window sensitivity vs primary lag models. Writes results/tables/robustness.md."""
import pandas as pd

import util as MT
from config import MARKETS, RESULTS
from evaluate import load_forecasts

T = RESULTS / "tables"


def mape(g):
    return ((g.actual - g.forecast).abs() / g.actual).mean() * 100


def main():
    rows, sens = [], []
    for mk in MARKETS:
        try:
            df = load_forecasts(mk)
        except FileNotFoundError:
            continue
        idx = sorted(df["idx"].unique())
        halves = {"first26": idx[:26], "last26": idx[26:]}
        for h, ii in halves.items():
            sub = df[df.idx.isin(ii)]
            per = sub.groupby(["model", "seed"]).apply(mape).groupby("model").mean()
            for mdl, v in per.items():
                rows.append({"market": mk, "window": h, "model": mdl, "MAPE": v})
        sp = RESULTS / "forecasts" / f"{mk}_sens.csv"
        if sp.exists():
            s = pd.read_csv(sp)
            base = df[df.model.isin(["SVR", "DT", "RF", "GB", "XGB"])]
            for m_ws, g in s.groupby("model"):
                prim = base[base.model == m_ws[:-3]].groupby("seed").apply(mape).mean()
                sens.append({"market": mk, "model": m_ws[:-3], "primary_MAPE": prim, "within_season_MAPE": mape(g)})
    r = pd.DataFrame(rows)
    out = ["# Robustness (generated by src/robustness.py)\n", "## Half-window stability: MAPE by test half\n"]
    for h in ("first26", "last26"):
        p = r[r.window == h].pivot(index="model", columns="market", values="MAPE")
        p = p.reindex([x for x in MT.ORDER if x in p.index])
        out += [f"### {h}\n", MT.md(p) + "\n"]
        best = p.idxmin()
        out.append("Lowest-MAPE model: " + "; ".join(f"{c}: {best[c]}" for c in p.columns) + "\n")
    if sens:
        out += ["## Within-season windows (L=4) vs primary lag models\n", MT.md(pd.DataFrame(sens).set_index("market")) + "\n"]
    (T / "robustness.md").write_text("\n".join(out), encoding="utf-8")
    print("written", T / "robustness.md")


if __name__ == "__main__":
    main()
