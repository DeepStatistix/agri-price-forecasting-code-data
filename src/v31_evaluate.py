"""Evaluation (test, h = 1..8): metrics, pooled and per-market DM for the comparisons, ablation, MCS.
Writes results/tables/v31_*.csv and V31_SUMMARY.md"""
import numpy as np
import pandas as pd

import data
from config import MARKETS, RESULTS
from evaluate import holm, mcs
from util import md
from mh_evaluate import dm_hln_h, mase_scale
from v3_evaluate import load_market

T = RESULTS / "tables"
H8 = list(range(1, 9))
N_EVAL = 52
NEW = ["V31_stack", "V31_stack_vgated", "V31_comb", "ABL_B3_stack", "ABL_B3_mean", "ABL_B5_stack", "ABL_B5_mean",
       "ABL_B1_stack", "ABL_B1_mean"]
FAMILIES = {   # (family, model, reference); Holm within family x horizon
    "stacker vs mean of its own pool": [("ABL_B3_stack", "ABL_B3_mean"), ("ABL_B5_stack", "ABL_B5_mean"), ("ABL_B1_stack", "ABL_B1_mean")],
    "pooled information (mean of pool)": [("ABL_B1_mean", "ABL_B3_mean"), ("ABL_B5_mean", "ABL_B3_mean")],
    "pooled information (stacker)": [("ABL_B1_stack", "ABL_B3_stack"), ("ABL_B5_stack", "ABL_B3_stack")],
    "vs simple references": [(m, r) for m in ("V31_stack", "V31_stack_vgated", "V31_comb") for r in ("Naive", "ETS", "Comb_Mean")],
    "vs v3 combination": [("V31_stack", "V3_comb"), ("V31_comb", "V3_comb")],
}


def load(mk):
    df = load_market(mk)
    f = pd.read_csv(RESULTS / "v31" / "forecasts" / "v31_final.csv")
    f = f[f["market"] == mk]
    return pd.concat([df, f], ignore_index=True)


def main():
    d = data.load_all()
    summ, pl, mcs_rows = [], {}, []
    for mk in MARKETS:
        df = load(mk)
        df["e"] = df["actual"] - df["forecast"]
        df["ape"] = df["e"].abs() / df["actual"] * 100
        per = df.groupby(["model", "seed", "h"]).agg(MAPE=("ape", "mean"), MAE=("e", lambda x: np.mean(np.abs(x)))).reset_index()
        per["MASE"] = per["MAE"] / mase_scale(mk, d)
        s = per.groupby(["model", "h"])[["MAPE", "MASE"]].mean().reset_index()
        s.insert(0, "market", mk)
        summ.append(s)
        df["se"] = df["e"] ** 2
        sc2 = float(data.series(d, mk)["MODAL"].astype(float).mean()) ** 2
        for h in H8:
            L = df[df["h"] == h].groupby(["target", "model"])["se"].mean().unstack("model").sort_index()
            pl[(mk, h)] = L / sc2
            keep = [c for c in L.columns if c != "SeasonalNaive"]
            for stat, pv in mcs(L[keep], alpha=0.10).items():
                for k, v in pv.items():
                    mcs_rows.append({"market": mk, "h": h, "statistic": stat, "model": k, "in_set_10": v >= 0.10})
        print("done", mk, flush=True)
    S = pd.concat(summ, ignore_index=True)
    S.to_csv(T / "v31_metrics.csv", index=False)
    MC = pd.DataFrame(mcs_rows)
    MC.to_csv(T / "v31_mcs.csv", index=False)

    rows = []
    for fam, pairs in FAMILIES.items():
        for h in H8:
            common = pl[(MARKETS[0], h)].index
            fr = []
            for mod, ref in pairs:
                lm = sum(pl[(mk, h)].loc[common, mod] for mk in MARKETS) / len(MARKETS)
                lr = sum(pl[(mk, h)].loc[common, ref] for mk in MARKETS) / len(MARKETS)
                st, p = dm_hln_h(lr, lm, h)
                fr.append({"family": fam, "h": h, "model": mod, "reference": ref, "DM": st, "p_raw": p,
                           "rel_loss_change_pct": 100 * (lm.mean() - lr.mean()) / lr.mean()})
            for r, pa in zip(fr, holm([r["p_raw"] for r in fr])):
                r["p_holm"] = pa
            rows += fr
    P = pd.DataFrame(rows)
    P.to_csv(T / "v31_pooled_dm.csv", index=False)

    out = ["# Results (generated by src/v31_evaluate.py), horizons 1..8, test = last 52 weeks per market\n"]
    pm = S.groupby(["model", "h"])["MAPE"].mean().unstack("h")
    order = ["Naive", "ETS", "Comb_Mean", "V3_comb", "V3_stack"] + NEW
    out += ["## Mean MAPE over six markets (%)\n", md(pm.reindex([o for o in order if o in pm.index])) + "\n"]
    rel = pm.div(pm.loc["Naive"], axis=1) * 100 - 100
    out += ["## Relative to Naive (%; negative = better)\n", md(rel.reindex([o for o in order if o in rel.index]).round(1)) + "\n"]
    piv = S.pivot_table(index=["market", "h"], columns="model", values="MAPE")
    wins = pd.DataFrame({m: (piv[m] < piv["Naive"]).groupby("h").sum() for m in NEW}).T.astype(int)
    out += ["## Markets (of 6) with lower MAPE than Naive\n", md(wins) + "\n"]
    sel = pd.read_csv(RESULTS / "v31" / "tuning" / "v31_selected.csv")
    out += ["## Selected on validation (550 configurations)\n", md(sel) + "\n"]
    for fam in FAMILIES:
        q = P[P["family"] == fam].drop(columns="family")
        out += [f"## Pooled DM: {fam} (positive DM = model better than reference; Holm within horizon and family)\n",
                md(q.round(3).set_index("h")) + "\n"]
    n_in = MC[(MC.statistic == "R") & MC.in_set_10].groupby(["market", "h"]).size()
    out += [f"## MCS (T_R, alpha 0.10): models in the set per cell: min {n_in.min()}, max {n_in.max()}\n"]
    cnt = {m: int(((MC.model == m) & (MC.statistic == "R") & MC.in_set_10).sum()) for m in NEW + ["Naive", "ETS"]}
    out += [f"Cells (of 48) in which the model is in the 90% set: {cnt}\n"]
    (T / "V31_SUMMARY.md").write_text("\n".join(out), encoding="utf-8")
    print("written")


if __name__ == "__main__":
    main()
