"""Evaluation, horizons 1..8: metrics, per-market and pooled Diebold-Mariano (HLN), MCS.
Reads v2 base/stack forecasts, v3 global models and v3 stackers. Writes results/tables/v3_*.csv and V3_SUMMARY.md"""
import numpy as np
import pandas as pd

import data
from config import MARKETS, RESULTS
from evaluate import holm, mcs
from util import md
from mh_evaluate import dm_hln_h, mase_scale

T = RESULTS / "tables"
FDIR = RESULTS / "mh" / "forecasts"
VDIR = RESULTS / "v3" / "forecasts"
H8 = list(range(1, 9))
N_EVAL = 52
TESTED = ["V3_stack", "V3_comb", "V3_stack_by_h"]
ALL_REF = ["Naive", "ETS"]
ORDER = ["Naive", "SeasonalNaive", "ETS", "ARIMA", "SVR", "RNN", "LSTM", "DT", "RF", "GB", "XGB", "G_Ridge", "G_RF",
         "G_XGB", "G_MLP", "Comb_Mean", "Comb_Median", "HS_RF_orig", "HS_NNLS_orig", "HS_Ridge_orig", "Comb_tuned",
         "HS_tuned_mkt", "HS_tuned_glob", "V3_comb", "V3_stack", "V3_stack_by_h"]
PRICE_SCALE = {}


def load_market(mk):
    parts = []
    for k in ("classical", "tabular", "deep", "final"):
        for suf in ("", "_ext"):
            parts.append(pd.read_csv(FDIR / f"{mk}_mh_{k}{suf}.csv"))
    g = pd.read_csv(VDIR / "global.csv")
    parts.append(g[g["market"] == mk])
    f = pd.read_csv(VDIR / "v3_final.csv")
    parts.append(f[f["market"] == mk])
    df = pd.concat(parts, ignore_index=True)
    df = df[(df["h"].isin(H8)) & (df["model"] != "Custom_Boosting")]
    n = df["target"].max() + 1
    return df[df["target"] >= n - N_EVAL].copy()


def main():
    d = data.load_all()
    refs = pd.read_csv(T / "mh_references_chosen_on_validation.csv").set_index("market")
    summ, dm_rows, pooled_losses, mcs_rows = [], [], {}, []
    for mk in MARKETS:
        df = load_market(mk)
        sc = mase_scale(mk, d)
        df["e"] = df["actual"] - df["forecast"]
        df["ape"] = df["e"].abs() / df["actual"] * 100
        per = df.groupby(["model", "seed", "h"]).agg(MAPE=("ape", "mean"), MAE=("e", lambda x: np.mean(np.abs(x))),
                                                     RMSE=("e", lambda x: np.sqrt(np.mean(x ** 2)))).reset_index()
        per["MASE"] = per["MAE"] / sc
        s = per.groupby(["model", "h"])[["MAPE", "MAE", "RMSE", "MASE"]].mean().reset_index()
        s.insert(0, "market", mk)
        summ.append(s)
        df["se"] = df["e"] ** 2
        scale2 = float(data.series(d, mk)["MODAL"].astype(float).mean()) ** 2
        for h in H8:
            L = df[df["h"] == h].groupby(["target", "model"])["se"].mean().unstack("model").sort_index()
            pooled_losses[(mk, h)] = L / scale2
            m = s[s["h"] == h].set_index("model")["MAPE"]
            rf = {**refs.loc[mk].to_dict(), "Naive": "Naive", "ETS": "ETS"}
            for rk, ref in rf.items():
                rows = []
                for mod in TESTED:
                    st, p = dm_hln_h(L[ref], L[mod], h)
                    rows.append({"market": mk, "h": h, "model": mod, "reference_kind": rk, "reference": ref,
                                 "MAPE_model": m[mod], "MAPE_ref": m[ref], "pp_diff": m[mod] - m[ref], "DM": st, "p_raw": p})
                for r, pa in zip(rows, holm([r["p_raw"] for r in rows])):
                    r["p_holm"] = pa
                dm_rows += rows
            keep = [c for c in L.columns if c != "SeasonalNaive"]
            for stat, pv in mcs(L[keep], alpha=0.10).items():
                for k, v in pv.items():
                    mcs_rows.append({"market": mk, "h": h, "statistic": stat, "model": k, "in_set_10": v >= 0.10})
        print("done", mk, flush=True)
    S = pd.concat(summ, ignore_index=True)
    S.to_csv(T / "v3_metrics.csv", index=False)
    D = pd.DataFrame(dm_rows)
    D.to_csv(T / "v3_dm.csv", index=False)
    MC = pd.DataFrame(mcs_rows)
    MC.to_csv(T / "v3_mcs.csv", index=False)

    # pooled DM: scale-free squared-error loss averaged over the six markets, per target week
    pr = []
    for h in H8:
        common = pooled_losses[(MARKETS[0], h)].index
        for mod in TESTED + ["G_XGB", "G_RF", "G_Ridge", "HS_tuned_mkt", "Comb_tuned"]:
            for ref in ["Naive", "ETS", "Comb_Mean", "ARIMA"]:
                l_ref = sum(pooled_losses[(mk, h)].loc[common, ref] for mk in MARKETS) / len(MARKETS)
                l_mod = sum(pooled_losses[(mk, h)].loc[common, mod] for mk in MARKETS) / len(MARKETS)
                st, p = dm_hln_h(l_ref, l_mod, h)
                pr.append({"h": h, "model": mod, "reference": ref, "DM": st, "p_raw": p,
                           "rel_loss_change_pct": 100 * (l_mod.mean() - l_ref.mean()) / l_ref.mean()})
    P = pd.DataFrame(pr)
    P["p_holm"] = P.groupby(["h", "reference"])["p_raw"].transform(lambda x: holm(x.to_numpy()))
    P.to_csv(T / "v3_pooled_dm.csv", index=False)

    out = ["# Results, horizons 1..8 (generated by src/v3_evaluate.py)\n",
           "Test = last 52 weekly targets per market. 'V3_*' = stackers over 14 base models incl. pooled global learners, "
           "selected on validation only. MAPE in %, seed means.\n"]
    pm = S.groupby(["model", "h"])["MAPE"].mean().unstack("h")
    pm = pm.reindex([x for x in ORDER if x in pm.index])
    out += ["## Mean MAPE over the six markets\n", md(pm) + "\n"]
    rel = (pm.div(pm.loc["Naive"], axis=1) * 100 - 100)
    out += ["## Mean MAPE relative to Naive (% difference; negative = better than naive)\n", md(rel.round(1)) + "\n"]
    pm2 = S.groupby(["model", "h"])["MASE"].mean().unstack("h")
    out += ["## Mean MASE\n", md(pm2.reindex([x for x in ORDER if x in pm2.index]), 3) + "\n"]
    best = S.loc[S.groupby(["market", "h"])["MAPE"].idxmin()].pivot(index="market", columns="h", values="model")
    out += ["## Lowest-MAPE model per market and horizon\n", md(best.reindex(MARKETS)) + "\n"]
    piv = S.pivot_table(index=["market", "h"], columns="model", values="MAPE")
    wins = pd.DataFrame({mod: (piv[mod] < piv["Naive"]).groupby("h").sum() for mod in
                         ["V3_stack", "V3_comb", "V3_stack_by_h", "G_XGB", "G_RF", "G_Ridge", "ETS", "HS_tuned_mkt", "Comb_tuned"]}).T
    out += ["## Number of markets (of 6) where the model has lower MAPE than Naive\n", md(wins.astype(int)) + "\n"]
    sel = pd.read_csv(RESULTS / "v3" / "tuning" / "v3_selected.csv")
    out += ["## Configurations selected on validation\n", md(sel) + "\n"]
    out += ["## Pooled Diebold-Mariano (scale-free squared error averaged over six markets; positive DM = model better)\n",
            md(P[P["model"].isin(TESTED + ["G_XGB"]) & P["reference"].isin(["Naive", "ETS", "Comb_Mean"])]
               .round(3).set_index("h")) + "\n"]
    sig = D[D["p_holm"] < 0.05]
    out += ["## Per-market Holm-significant (p < 0.05) comparisons of V3 models\n",
            md(sig[["market", "h", "model", "reference_kind", "reference", "pp_diff", "DM", "p_holm"]].round(3).set_index("market"), 3)
            if len(sig) else "None.\n"]
    n_in = MC[(MC.statistic == "R") & MC.in_set_10].groupby(["market", "h"]).size()
    out += [f"\n## MCS (T_R, alpha 0.10): models in set per cell, min {n_in.min()}, max {n_in.max()}\n"]
    for mod in TESTED:
        t = MC[(MC.statistic == "R") & (MC.model == mod)].pivot(index="market", columns="h", values="in_set_10").reindex(MARKETS)
        out += [f"### {mod} in set?\n", md(t.astype(str)) + "\n"]
    (T / "V3_SUMMARY.md").write_text("\n".join(out), encoding="utf-8")
    print("written V3_SUMMARY.md")


if __name__ == "__main__":
    main()
